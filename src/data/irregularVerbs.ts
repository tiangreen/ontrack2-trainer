export function irregularVerbItems(): GapItem[] {
  return irregularVerbs.flatMap((v): GapItem[] => {
    const forms = `to ${v.base} – ${v.past} – ${v.participle}`;
    return [
      {
        kind: 'gap',
        id: `irregular-verbs-${v.base}-past`,
        prompt: `to ${v.base} (${v.de}) → simple past: ___`,
        answers: v.base === 'be' ? ['was/were', 'was', 'were', 'was were'] : [v.past],
        explanation: `${forms}: Die 2. Form brauchst du im simple past.`,
      },
      {
        kind: 'gap',
        id: `irregular-verbs-${v.base}-pp`,
        prompt: `to ${v.base} (${v.de}) → past participle: ___`,
        answers: [v.participle],
        explanation: `${forms}: Die 3. Form brauchst du im present perfect (have/has + 3. Form).`,
      },
    ];
  });
}
